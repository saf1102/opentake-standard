import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import contract from '../desktop/windows-update-manifest.cjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const metadata=JSON.parse(fs.readFileSync(path.join(root,'desktop/windows-version.json'),'utf8'));
const receipt=JSON.parse(fs.readFileSync(path.join(root,'release-source.json'),'utf8'));
const [installerArg,notesArg,outArg]=process.argv.slice(2);
if(!installerArg||!notesArg)throw Error('用法: node scripts/prepare-windows-release.mjs <安装包.exe> <更新说明.txt> [输出目录]');
const installer=path.resolve(installerArg),out=path.resolve(outArg||path.dirname(installer));
const name=`OpenTake-Standard-Setup-${pkg.version}-x64.exe`;
if(path.basename(installer)!==name||receipt.version!==pkg.version||receipt.windowsBuild!==metadata.windowsBuild||receipt.windowsRevision!==metadata.windowsRevision||receipt.modified)throw Error('安装包名称或源码构建凭据不匹配，请从干净的已提交源码构建');
const hash=crypto.createHash('sha256');for await(const chunk of fs.createReadStream(installer))hash.update(chunk);
const tag=`windows-v${pkg.version}-${metadata.windowsBuild}`;
const manifest=contract.windowsRelease({schemaVersion:1,product:pkg.name,platform:'win32',arch:'x64',channel:'stable',version:pkg.version,windowsBuild:metadata.windowsBuild,revision:metadata.windowsRevision,notes:fs.readFileSync(path.resolve(notesArg),'utf8').trim(),url:`https://github.com/${contract.repository}/releases/download/${tag}/${name}`,sha256:hash.digest('hex'),size:fs.statSync(installer).size});
if(!manifest)throw Error('Windows 发布清单无效');
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'windows-update.json'),JSON.stringify(manifest,null,2)+'\n');
fs.writeFileSync(path.join(out,'SHA256SUMS.txt'),`${manifest.sha256}  ${name}\n`);
console.log(JSON.stringify({version:pkg.version,windowsBuild:metadata.windowsBuild,tag,endpoint:contract.endpoint,output:out,published:false},null,2));
